"""Build the browser's offline catalogs from the reviewed UTF-8 source catalogs."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LANGUAGES = ["en", "ru", "fr", "de", "es", "it"]


def outputs():
    messages = {}
    for source in [ROOT / "src/catalog.txt", ROOT / "extension/catalog.txt"]:
        for line in source.read_text(encoding="utf-8").splitlines():
            row = line.split("|")
            assert len(row) == 6, f"Invalid catalog row: {line}"
            assert row[0] not in messages, f"Duplicate message: {row[0]}"
            assert all(value.strip() for value in row), f"Empty translation: {row[0]}"
            assert all(value.count("{}") == row[0].count("{}") for value in row), row[0]
            messages[row[0]] = row
    result = {ROOT / "extension/catalog.js":
              "// Generated by scripts/Build-Locales.py. Edit the source catalogs.\n"
              "export const catalogs = " + json.dumps(messages, ensure_ascii=False, indent=2) + ";\n"}
    for index, language in enumerate(LANGUAGES):
        result[ROOT / f"extension/_locales/{language}/messages.json"] = json.dumps({
            "extensionName": {"message": messages["WebsiteBlocker Companion"][index]},
            "extensionDescription": {"message": messages[
                "Apply your local WebsiteBlocker focus rules and schedules to website navigations."][index]},
        }, ensure_ascii=False, indent=2) + "\n"
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            assert path.read_text(encoding="utf-8") == content, f"Stale generated locale: {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print("Six complete browser catalogs and manifest locales verified." if args.check else "Built six browser catalogs.")
